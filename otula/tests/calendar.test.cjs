const fs=require('fs'),vm=require('vm'),assert=require('assert/strict'),path=require('path');
const app=fs.readFileSync(path.join(__dirname,'../dist/app.js'),'utf8');
const context={TextEncoder,document:{addEventListener(){}},crypto:require('crypto').webcrypto};
vm.createContext(context);
vm.runInContext(app.slice(app.indexOf('function icsEscape('),app.indexOf('function icsDate(')),context);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../dist/calendar.js'),'utf8'),context);
context.input=[{id:'sample',date:'2027-02-02',time:'10:30',title:'Załączniki, dokumenty; rozmowa',note:'Pierwsza linia\r\nDruga linia\rTrzecia\n'+ 'Zażółć gęślą jaźń. '.repeat(20),remind:7,revision:2}];
const encoded=vm.runInContext("calendarICS(input,'child-a',new Date('2026-11-21T10:00:00Z'))",context);
assert.ok(encoded.endsWith('\r\n'));
assert.ok(encoded.split('\r\n').every(line=>Buffer.byteLength(line,'utf8')<=75));
const unfolded=encoded.replace(/\r\n /g,'');
assert.ok(unfolded.includes('DTSTART:20270202T103000\r\n'));
assert.ok(unfolded.includes('TRIGGER:-P7D\r\n'));
assert.ok(unfolded.includes('SUMMARY:Otula: Załączniki\\, dokumenty\\; rozmowa\r\n'));
assert.ok(unfolded.includes('Pierwsza linia\\nDruga linia\\nTrzecia\\n'));
assert.ok(unfolded.includes('SEQUENCE:2\r\n'));
assert.ok(unfolded.includes('UID:child-a-sample@otula\r\n'));
context.input[0].remind=0;
const second=vm.runInContext("calendarICS(input,'child-b')",context);
assert.ok(second.includes('TRIGGER:PT0S\r\n'));
assert.ok(second.includes('UID:child-b-sample@otula\r\n'));
assert.ok(!second.includes('UID:child-a-'));
console.log('ICS: data, alarm, aktualizacja, osobne dzieci, polskie znaki i dlugosc linii OK');
