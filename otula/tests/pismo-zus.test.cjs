const assert=require('node:assert/strict');
const api=require('../dist/pismo-zus.js');
const d={kind:'request',benefit:'maternity',deadline:'2027-01-10',owner:'payer',missingDocument:'z3'};
assert.equal(api.assess(d,'2027-01-09').days,1);
assert.equal(api.assess(d,'2027-01-10').days,0);
assert.match(api.assess(d,'2027-01-11').deadline,/minął/);
assert.equal(api.daysUntil('2027-02-30','2027-01-01'),null);
assert.equal(api.daysUntil('2027-03-29','2027-03-28'),1,'Liczba dni nie zależy od zmiany czasu');
assert(!api.questions(d).includes('reason'));
assert(api.questions({kind:'refusal'}).includes('decisionScope'));
assert(!api.questions({kind:'refusal'}).includes('missingDocument'));
assert.deepEqual(api.sanitize({...d,pesel:'12345678901',name:'TEST',reason:'debt',decisionScope:'insurance'}),d,'Tylko nieidentyfikujące pola pisma');
assert(!api.sanitize({...d,kind:'notice'}).owner,'Zmiana sytuacji usuwa stare odpowiedzi');
assert.match(api.assess({kind:'approval',decisionScope:'insurance'}).next[0],/nie jest jeszcze decyzją o wypłacie/);
const refusal=api.assess({kind:'refusal',decisionScope:'insurance',reason:'debt'});
assert.match(refusal.reportedReason,/ratalny/);assert.match(refusal.next.join(' '),/nie zapewnia/);assert(!/przysługuje Ci|na pewno|wystarczy/.test(refusal.next.join(' ')));
assert.match(api.requestText(d),/Bardzo proszę/);assert.match(api.requestText(d),/Z-3/);assert.match(api.requestText(d),/Dziękuję/);
assert.match(api.requestText({},true),/stracie/);assert(!/płeć|imię dziecka|diagnoza/.test(api.supportMarkup()));
const ics=api.buildICS(d,new Date('2026-12-01T12:00:00Z'));
assert.match(ics,/DTSTART;VALUE=DATE:20270110\r\n/);assert.match(ics,/DTEND;VALUE=DATE:20270111/);assert.match(ics,/TRIGGER:-P1D/);assert.match(ics,/CLASS:PRIVATE/);assert(!ics.includes('macierzyński'),'Alarm nie ujawnia rodzaju świadczenia');
assert(ics.split('\r\n').every(line=>Buffer.byteLength(line,'utf8')<=75),'RFC5545 składanie wg bajtów UTF-8');
assert.throws(()=>api.buildICS({...d,deadline:'unknown'}),/termin/);
console.log('Pismo ZUS: wybory, odrębna decyzja ubezpieczeniowa, deklarowane powody, data/ICS i łagodne wsparcie OK');
