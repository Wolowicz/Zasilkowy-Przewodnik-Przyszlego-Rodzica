const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const crypto=require('node:crypto');
const dir=path.join(__dirname,'../dist');
const api=require(path.join(dir,'wniosek-pdf.js'));
const PDFLib=require(path.join(dir,'assets/wniosek-pdf-lib.min.js'));
const jsPDF=require(path.join(dir,'assets/report-jspdf.min.js')).jsPDF;
const fonts={window:{}};vm.runInNewContext(fs.readFileSync(path.join(dir,'assets/report-fonts.js'),'utf8'),fonts);
const schema=JSON.parse(fs.readFileSync(path.join(dir,'assets/zus-zam-fields.json'),'utf8'));
const template=fs.readFileSync(path.join(dir,'assets/zus-zam-2026-10.pdf'));
const assets={PDFLib,jsPDF,schema,template,font:fonts.window.otulaReportFonts.Sans};
const own={firstName:'Małgorzata',lastName:'Żółć-Łącka',personDob:'1995-02-11',identity:'PASZPORT TEST123',house:'12',city:'Łódź',postal:'90-001',payerName:'PŁATNIK TESTOWY',payerNip:'1234563218',reason:'birth',children:'JAN TESTOWY, 20.11.2026, ŁÓDŹ',periods:[{kind:'maternity',from:'2026-11-20',to:'2027-04-08'}],filledDate:'2026-11-21',reviewed:true};
async function run(){
 assert.equal(crypto.createHash('sha256').update(template).digest('hex'),schema.sha256,'Publiczny wzór odpowiada zbadanej mapie');
 assert.equal(schema.fields.length,85);assert.equal(schema.pages,7);
 assert.deepEqual(api.validate(own),[]);
 assert(api.validate({...own,reviewed:false}).some(s=>s.includes('potwierdzenie')));
 assert(api.validate({...own,periods:[{kind:'maternity',from:'2027-02-30',to:'2027-03-31'}]}).length,'Nieprawdziwa data jest odrzucona');
 assert(api.validate({...own,periods:[{kind:'maternity',from:'2027-04-01',to:'2027-03-31'}]}).length);
 assert(api.validate({...own,personDob:'',pesel:''}).length,'Nie generuj bez wymaganej identyfikacji');
 const normalized=api.normalize({answers:{event:'birth',eventDate:'2027-01-12',birthWeight:900,gestationWeeks:29,zaZyciem:'yes'},periods:[{kind:'parental',from:'2027-05-01',to:'2027-06-01'}]});
 assert.equal(normalized.eventDate,'2027-01-12');assert.equal(normalized.grams,900);
 const vals=api.fieldValues(own);assert.equal(vals['1.Imie'],'Małgorzata');assert.equal(vals['2.macierzynskiego'],true);assert.equal(vals['2.Okres'],'20.11.2026 – 08.04.2027');
 assert(!vals['2.informuje'],'Nie zaznaczaj oświadczenia 81,5% na podstawie samej daty');
 const father={...own,periods:[{kind:'paternity',from:'2027-01-01',to:'2027-01-07'}],paternityPart:'1',previousPaternity:'no'};
 const fv=api.fieldValues(father);assert.equal(fv['5.NIE2'],true);assert(!fv['5.NIE'],'Wizualnie sprawdzona strona5: NIE2 to poprzedni ojcowski, NIE to drugi rodzic');
 assert(api.validate({...father,previousPaternity:''}).length,'Brak odpowiedzi nie oznacza nie');
 const hospital={...own,periods:[{kind:'supplementary',from:'2027-04-09',to:'2027-04-22'}],maternityEnd:'2027-04-08',hospitalCondition:'between28and37',hospitalConfirmed:true,stays:[{from:'2026-11-20',to:'2026-11-27'}],otherUses:'no'};
 assert.deepEqual(api.validate(hospital),[]);const hv=api.fieldValues(hospital);assert.equal(hv['3.przerwaniem4B'],true);assert.equal(hv['5.NIE'],true);assert(!hv['5.NIE2']);
 assert(api.validate({...hospital,hospitalConfirmed:false}).length);
 const death={...own,reason:'loss',children:'',lossDate:'2026-11-20',lossDocument:'medical'};
 assert.deepEqual(api.validate(death),[],'Nie wymagaj imienia ani płci po stracie');
 assert.match(api.fieldValues(death)['3.Tekst1'],/zaświadczenie/);
 assert(api.validate({...death,lossDocument:''}).length);
 assert.equal(api.normalize({answers:{event:'childDeath'}}).reason,'loss');
 const bytes=await api.generatePdf(own,assets);const pdf=await PDFLib.PDFDocument.load(bytes);
 assert.equal(pdf.getPageCount(),7);assert.equal(pdf.getForm().getFields().length,0,'PDF do druku nie ma aktywnych pól/skryptów formularza');
 assert.equal(pdf.getTitle(),'ZAM – wniosek do sprawdzenia i podpisu');
 assert(bytes.byteLength>50000);assert(!Object.keys(vals).some(k=>/podpis|signature/i.test(k)),'Podpis zawsze pusty');
 const resources=pdf.getPage(0).node.Resources();assert(resources,'Font i nakładka są osadzone lokalnie');
 await assert.rejects(()=>api.generatePdf({...own,firstName:'A'.repeat(2000)},assets),/za długa|nie mieści/,'Nadmiar nie jest cicho ucinany');
 await assert.rejects(()=>api.generatePdf(own,{...assets,schema:{...schema,version:'2030-01-01'}}),/wersja|Wersja/);
 const fake=await PDFLib.PDFDocument.create();fake.addPage();
 const simple=await api.composePdf({template:await fake.save(),schema:{pages:1,fields:[{page:1,name:'name',rect:[40,40,300,62],type:'Text'}]},values:{'1.name':'ZAŻÓŁĆ GĘŚLĄ JAŹŃ'},title:'Test syntetyczny'},assets);
 assert.equal((await PDFLib.PDFDocument.load(simple)).getPageCount(),1,'Wspólny helper obsługuje też inny urzędowy wzór');
 console.log('ZAM PDF: 7 stron, polskie dane, puste podpisy, warianty i data2027, świadome oświadczenia, przepełnienie oraz mapa oficjalnych pól OK');
}
run().catch(e=>{console.error(e);process.exitCode=1;});
